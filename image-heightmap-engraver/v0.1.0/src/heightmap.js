export function toGrayscale(imageData, invert = false) {
  const { data, width, height } = imageData;
  const pixels = new Uint8Array(width * height);
  for (let i = 0, p = 0; i < data.length; i += 4, p += 1) {
    const gray = Math.round(0.2126 * data[i] + 0.7152 * data[i + 1] + 0.0722 * data[i + 2]);
    pixels[p] = invert ? 255 - gray : gray;
  }
  return { pixels, width, height };
}

const fmt = (n) => Number(n).toFixed(3);
export function generateHeightmapGcode({ pixels, width, height, sizeX, sizeY, maxDepth, feed, plunge, safeZ, originX = 0, originY = 0 }) {
  if (!pixels || pixels.length !== width * height) throw new Error('Load an image before generating G-code.');
  if (![sizeX, sizeY, maxDepth, feed, plunge, safeZ].every((n) => Number.isFinite(Number(n)) && Number(n) > 0)) throw new Error('Dimensions, maximum depth, feed, plunge, and safe Z must be greater than zero.');
  const dx = width > 1 ? sizeX / (width - 1) : 0, dy = height > 1 ? sizeY / (height - 1) : 0;
  const point = (x, y) => ({ x: Number(originX) + x * dx, y: Number(originY) + sizeY - y * dy, z: -(pixels[y * width + x] / 255) * Number(maxDepth) });
  const lines = ['(Grayscale image heightmap generated by Image Heightmap Engraver)', `(Image ${width} x ${height} pixels; engraving area ${fmt(sizeX)} x ${fmt(sizeY)} mm)`, `(Grayscale mapping: 0 = Z0; 255 = Z-${fmt(maxDepth)} mm; lower-left origin)`, '(Review and simulate before running; this plugin does not start jobs.)', 'G21', 'G90', 'G17', 'G94', 'G54', `G0 Z${fmt(safeZ)}`];
  for (let y = 0; y < height; y += 1) {
    const reverse = y % 2 === 1, first = reverse ? width - 1 : 0, start = point(first, y);
    lines.push(`G0 X${fmt(start.x)} Y${fmt(start.y)}`, `G1 Z${fmt(start.z)} F${Math.round(plunge)}`);
    for (let step = 1; step < width; step += 1) { const p = point(reverse ? width - 1 - step : step, y); lines.push(`G1 X${fmt(p.x)} Y${fmt(p.y)} Z${fmt(p.z)} F${Math.round(feed)}`); }
    lines.push(`G0 Z${fmt(safeZ)}`);
  }
  lines.push('M5', 'M30', ''); return lines.join('\n');
}
